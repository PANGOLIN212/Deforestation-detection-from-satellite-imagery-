# ## 10. Area estimates and their bias
# Forest managers report **hectares**, not pixels. A map's area is biased when its precision and recall differ: if we find 90% of the true pixels (recall) but only 80% of what we flag is correct (precision), the mapped area is not the true area. In expectation, `true area ≈ mapped area × precision / recall`.
#
# **A trap to avoid.** If precision and recall are measured on the same data and then used to adjust the total area, the adjusted total equals the true total **by arithmetic**, which looks like a success but proves nothing. To test the idea honestly, we adjust each scene using the precision and recall of the **other seven scenes only**.

# %%
cnt = []
for k in range(len(scenes)):
    m = metrics(final[k][~cloud_det[k]], truth[k][~cloud_det[k]]); cnt.append((m["tp"], m["fp"], m["fn"]))
cnt = np.array(cnt)
rows = []
for k in range(len(scenes)):
    tp_o, fp_o, fn_o = np.delete(cnt, k, axis=0).sum(axis=0)
    P_o, R_o = tp_o / (tp_o + fp_o), tp_o / (tp_o + fn_o)
    mapped = (final[k] & ~cloud_det[k]).sum() * HA_PER_PIXEL; true = (truth[k] & ~cloud_det[k]).sum() * HA_PER_PIXEL
    rows.append({"scene": scenes[k]["name"], "true_ha": true, "mapped_ha": mapped, "adjusted_ha": mapped * P_o / R_o})
area = pd.DataFrame(rows)
for c in ["mapped", "adjusted"]: area[f"{c}_error_%"] = (area[f"{c}_ha"] / area["true_ha"] - 1) * 100
tot = area[["true_ha", "mapped_ha", "adjusted_ha"]].sum()
big = area[area["true_ha"] > 10]
print(f"Total over all scenes: true {tot['true_ha']:.0f} ha | mapped {tot['mapped_ha']:.0f} ha ({tot['mapped_ha'] / tot['true_ha'] - 1:+.1%}) | adjusted {tot['adjusted_ha']:.0f} ha ({tot['adjusted_ha'] / tot['true_ha'] - 1:+.1%})")
print(f"Scenes with more than 10 ha: mean absolute error per scene {big['mapped_error_%'].abs().mean():.1f}% mapped, {big['adjusted_error_%'].abs().mean():.1f}% adjusted")
fig, ax = plt.subplots(figsize=(5.4, 4.6))
