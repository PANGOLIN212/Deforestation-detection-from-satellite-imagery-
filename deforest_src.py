# %% [markdown]
# ## 6. Machine learning on per-pixel features
#
# For each pixel we build a feature vector from both dates (see `src/features.py`):
#
# | Group | Features |
# |-------|----------|
# | **Date 1** | Six bands and four indices (NDVI, NBR, NDMI, bare-soil index): was it forest? |
# | **Date 2** | The same ten |
# | **Difference** | Change in every band and index, plus the spectral change magnitude |
# | **Context** | Neighbourhood means and variation of the change (5 and 11 pixels), and the share of forest-like pixels around (11 and 21 pixels) |
#
# We train a **random forest** and compare feature sets with leave-scene-out cross-validation. Training uses all positive pixels plus a random sample of negatives, and prediction covers every pixel of the held-out scenes.

# %%
t0_ = time.time()
stacks = [feature_stack(s["t1"], s["t2"]) for s in scenes]
F = [st[0] for st in stacks]; names = stacks[0][1]; groups = np.array(stacks[0][2])
print(f"Feature stacks: {len(names)} features per pixel, {sum(f.shape[0] for f in F) / 1e3:.0f}k pixels ({time.time() - t0_:.0f}s)")
col_sets = {
    "Difference only": np.where(groups == "difference")[0],
    "Difference + both dates": np.where(np.isin(groups, ["difference", "date 1", "date 2"]))[0],
    "All features (+ context)": np.arange(len(names)),
}
def make_rf(): return RandomForestClassifier(n_estimators=100, max_depth=16, min_samples_leaf=5, class_weight="balanced_subsample", n_jobs=1, random_state=0)

def train_sample(train_scenes, max_pos=8000, neg_ratio=3, seed=0):
    r = np.random.default_rng(seed); rows_p, rows_n = [], []
    for k in train_scenes:
        t = truth[k].ravel(); ok = ~scenes[k]["unobservable"].ravel() | t
        rows_p += [(k, i) for i in np.nonzero(t)[0]]; rows_n += [(k, i) for i in np.nonzero(~t & ok)[0]]
    r.shuffle(rows_p); rows_p = rows_p[:max_pos]; r.shuffle(rows_n); rows_n = rows_n[:max_pos * neg_ratio]
    sel = rows_p + rows_n
    X_ = np.stack([F[k][i] for k, i in sel]); y_ = np.array([1] * len(rows_p) + [0] * len(rows_n))
    return X_, y_

def oof_probabilities(cols, seed=0):
    probs = [None] * len(scenes); importances = []
    for test in SCENE_FOLDS:
        train = [k for k in range(len(scenes)) if k not in test]
        X_, y_ = train_sample(train, seed=seed)
        m = make_rf().fit(X_[:, cols], y_); importances.append(m.feature_importances_)
        for k in test: probs[k] = m.predict_proba(F[k][:, cols])[:, 1].reshape(truth[k].shape)
    return probs, np.mean(importances, axis=0)

t0_ = time.time()
oof = {}; imp_all = None
for nm, cols in col_sets.items():
    oof[nm], imp = oof_probabilities(cols)
    if nm.startswith("All"): imp_all = imp
print(f"Trained 3 feature sets x 4 folds in {time.time() - t0_:.0f}s")

rows = []
for nm in col_sets:
    for use_mask in (False, True):
        pred = [(oof[nm][k] >= 0.5) for k in range(len(scenes))]
        m = evaluate(pred, use_mask=use_mask)
        rows.append({"features": nm, "cloud mask applied": use_mask, **{k: m[k] for k in ["precision", "recall", "f1", "iou"]}})
ml_tbl = pd.DataFrame(rows)
ml_tbl.round(3)

# %% [markdown]
# **Reading the table.** Each extra feature group helps: seeing the *starting spectrum* tells the model whether it was forest, and the *neighbourhood context* separates compact clearings from scattered noise. The effect of the cloud mask shows how much of the remaining error is cloud. Note the **recall is high but precision is low** at the default 0.5 threshold. We fix that in Section 7.
#
# ### Why leave-scene-out? What a random pixel split would claim
# To see the problem with the common shortcut, we run the **same model with the same pixel sampling**, changing only how pixels are split: a **random split of pixels** (neighbours end up on both sides) versus a **scene-wise split** (whole scenes held out). Both are scored on randomly sampled pixels with the default threshold, so the only difference is the leakage.

# %%
r = np.random.default_rng(3)
samp = {k: r.choice(truth[k].size, 6000, replace=False) for k in range(len(scenes))}
def sample_xy(ks):
    X_ = np.vstack([F[k][samp[k]] for k in ks]); y_ = np.concatenate([truth[k].ravel()[samp[k]] for k in ks])
    return X_, y_.astype(int)
Xa, ya = sample_xy(range(len(scenes)))
tr_m = r.random(len(ya)) < 0.7
rf_leaky = make_rf().fit(Xa[tr_m], ya[tr_m])
leaky = metrics(rf_leaky.predict(Xa[~tr_m]).astype(bool), ya[~tr_m].astype(bool))
preds_, true_ = [], []
for test in SCENE_FOLDS:
    tr = [k for k in range(len(scenes)) if k not in test]
    Xt, yt = sample_xy(tr); Xv, yv = sample_xy(test)
    preds_.append(make_rf().fit(Xt, yt).predict(Xv)); true_.append(yv)
honest = metrics(np.concatenate(preds_).astype(bool), np.concatenate(true_).astype(bool))
print(f"Random pixel split (leaky)       : precision {leaky['precision']:.3f}, recall {leaky['recall']:.3f}, F1 {leaky['f1']:.3f}, IoU {leaky['iou']:.3f}")
print(f"Scene-wise split (honest)        : precision {honest['precision']:.3f}, recall {honest['recall']:.3f}, F1 {honest['f1']:.3f}, IoU {honest['iou']:.3f}")
print(f"Overstatement from leakage: {leaky['f1'] - honest['f1']:+.3f} F1")

# %% [markdown]
# **Honest note on this result.** The gap is negligible here, so this experiment does **not** demonstrate a leakage problem. All eight scenes come from the same simulator, so they are nearly interchangeable and a model trained on some scenes transfers to the others almost as well as to held-out pixels of the same scenes. Real imagery differs much more from place to place and date to date (atmosphere, season, sensor, terrain), so scene-wise or region-wise validation is still the correct design for real data, but you should expect it to matter there and should not take this synthetic result as evidence that it does not.

