# ## Limitations
# * **Synthetic data.** Real scenes contain far more variety: terrain shadows, haze, plantation harvests, fire scars, rivers and cloud edges that are not as clean as here. Expect lower scores
# * **Plantations.** Kenya has many planted forests (such as cypress, pine and eucalyptus) that are harvested on a cycle. Harvest looks exactly like deforestation to a spectral change detector, so a real system needs a plantation mask or local knowledge
# * **Resolution.** At 10 m, clearings below about 0.2 ha (a few pixels) are hard to see. Higher-resolution imagery or radar (Sentinel-1, which sees through cloud) would help
# * **Two dates only.** Dense time series (many images per year) allow much better handling of clouds, seasonality and regrowth
# * **Reference labels.** Real labels come from human interpreters or products such as global forest-loss maps, and these have errors of their own
# * **Area estimates** need a design-based sample of reference points to give honest confidence intervals
#
# ## Responsible use
# * Alerts should be **verified by people** (rangers, local forest officers) before any enforcement action
# * Flagging a clearing is not the same as identifying who did it, and communities living near forests can be affected by enforcement. Involve them and use the data to support restoration and livelihoods, not only penalties
# * Satellite monitoring should complement, not replace, local knowledge
