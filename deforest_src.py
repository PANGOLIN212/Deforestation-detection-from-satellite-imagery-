# %% [markdown]
# ## 7. Choosing the threshold, and post-processing
#
# **Probability threshold.** The forest was trained on a rebalanced sample (about 25% positives) while the real share of deforested pixels is only a few percent, so its probabilities are inflated and the default 0.5 is too low. We choose the threshold that maximises F1 on the **out-of-fold predictions of the other three folds**, then apply it to the held-out scenes. The threshold for a scene is never tuned on that scene.
#
# **Minimum mapping unit.** Raw pixel predictions are speckled. Forest-monitoring programmes use a **minimum mapping unit (MMU)**: patches smaller than a set area are discarded. We first apply a 3 x 3 morphological opening to remove thin spurs, then drop patches below the MMU, and choose the MMU from the results.

# %%
def remove_small(mask, min_px):
    if min_px <= 1: return mask
    lab, n = ndi.label(mask); sizes = np.bincount(lab.ravel()); keep = sizes >= min_px; keep[0] = False
    return keep[lab]
def postprocess(prob, thr=0.5, mmu=20, open_=True):
    m = prob >= thr
    if open_: m = ndi.binary_opening(m, structure=np.ones((3, 3), bool))
    return remove_small(m, mmu)

probs_final = oof["All features (+ context)"]
fold_of_scene = {k: fi for fi, fold in enumerate(SCENE_FOLDS) for k in fold}
thr_grid = np.arange(0.30, 0.96, 0.05)
def f1_at(thr, ks):
    p = np.concatenate([(probs_final[k] >= thr)[~cloud_det[k]] for k in ks]); t = np.concatenate([truth[k][~cloud_det[k]] for k in ks])
    return metrics(p, t)["f1"]
fold_thr = {}
for fi, fold in enumerate(SCENE_FOLDS):
    others = [k for k in range(len(scenes)) if k not in fold]
    fold_thr[fi] = round(float(max(thr_grid, key=lambda t: f1_at(t, others))), 2)
scene_thr = [fold_thr[fold_of_scene[k]] for k in range(len(scenes))]
print("Thresholds chosen for each fold (from the other folds only):", fold_thr)
pred_05 = [(probs_final[k] >= 0.5) & ~cloud_det[k] for k in range(len(scenes))]
pred_sel = [(probs_final[k] >= scene_thr[k]) & ~cloud_det[k] for k in range(len(scenes))]
cmp_thr = pd.DataFrame({"default threshold 0.5": evaluate(pred_05, use_mask=True), "fold-selected threshold": evaluate(pred_sel, use_mask=True)}).T[["precision", "recall", "f1", "iou"]]
print(cmp_thr.round(3).to_string())

rows = []
