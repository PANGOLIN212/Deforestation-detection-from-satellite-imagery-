# %% [markdown]
# # Deforestation Detection from Satellite Imagery: A Kenyan Forest Case Study
#
# **Why Kenya, and why now.** Kenya's five "water towers" (the Mau Forest Complex, the Aberdare Range, Mount Kenya, Mount Elgon and the Cherangani Hills) feed the rivers that supply cities, farms, tea estates and hydropower. They face pressure from illegal logging, charcoal burning, farmland expansion and settlement. Forest managers cannot patrol hundreds of thousands of hectares on foot, so **satellite change detection** is one of the few ways to see clearing soon after it happens.
#
# **The task.** Given two images of the same place at two dates, label every pixel as **deforested** (forest at date 1, cleared by date 2) or **not**. This is *change detection*, which is harder than classifying a single image, because most apparent changes are **not** deforestation:
#
# | Change that is NOT deforestation | Why it fools simple methods |
# |----------------------------------|-----------------------------|
# | Seasonal drying of grass and crops | Greenness (NDVI) drops, just as it does when forest is cleared |
# | Crop harvest | Bare soil appears, just as after clearing |
# | Clouds and cloud shadows | Large spectral change with no change on the ground |
# | Selective logging (canopy thinning) | The forest is still there, so it is degradation, not deforestation |
# | Image misregistration and sensor noise | Spurious change at every edge |
#
# **What we do**
# 1. Build realistic **Sentinel-2-style** scenes (six bands, two dates) with these confounders and exact truth maps
# 2. Show how far classic **index-threshold** methods (ΔNDVI, ΔNBR) get, and exactly *why* they fail
# 3. Add a **cloud and shadow mask**
# 4. Train a **random forest on per-pixel spectral, temporal and neighbourhood features**, evaluated with **leave-scene-out** cross-validation
# 5. Clean the map with a **minimum mapping unit**, then test **patch-level detection**, **area estimates** and **error sources**
#
# > **Data note.** The scenes are **synthetic** and generated by `src/synthetic_scenes.py`. Spectral signatures are typical illustrative values, and the scene names only echo Kenyan forest blocks. Results here show the method, **not** the state of any real forest. The pipeline expects arrays shaped `(6, H, W)` per date, so real Sentinel-2 chips can be dropped in (see the README).

