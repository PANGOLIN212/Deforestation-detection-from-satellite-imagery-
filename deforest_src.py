# %% [markdown]
# Deforestation, crop harvest, clouds and, to a lesser degree, seasonal drying all overlap in their NDVI change. No threshold will separate them. We need **context** (was it forest?), **other bands** (SWIR separates bare soil from vegetation) and **neighbourhood** information (clearings are compact patches, noise is scattered).
#
# ## 3. Evaluation design: leave-scene-out
#
# Neighbouring pixels are almost identical, so a random pixel split would put near-copies of every test pixel into the training set. To measure how the method works on **a new place**, we hold out **whole scenes**: 4 folds, each testing on 2 scenes the model never saw.
#
# **Metrics** (pixel level, on the pixels we are willing to make a call on):
# * **Precision:** of the pixels we flag, how many are truly deforested
# * **Recall:** of the truly deforested pixels, how many we find
# * **F1** and **IoU** (intersection over union), which balance the two
#
# **The evaluation domain.** Pixels flagged by our own cloud/shadow mask are excluded (they are "no data" and would be reported as such). Pixels the mask *misses* stay in, so leftover cloud errors count against us.

# %%
SCENE_FOLDS = [[0, 1], [2, 3], [4, 5], [6, 7]]
def metrics(pred, truth):
    tp, fp, fn = (pred & truth).sum(), (pred & ~truth).sum(), (~pred & truth).sum()
    return {"precision": tp / max(tp + fp, 1), "recall": tp / max(tp + fn, 1), "f1": 2 * tp / max(2 * tp + fp + fn, 1), "iou": tp / max(tp + fp + fn, 1), "tp": int(tp), "fp": int(fp), "fn": int(fn)}

ind1 = [indices(s["t1"]) for s in scenes]; ind2 = [indices(s["t2"]) for s in scenes]
d_ndvi = [b["ndvi"] - a["ndvi"] for a, b in zip(ind1, ind2)]
d_nbr = [b["nbr"] - a["nbr"] for a, b in zip(ind1, ind2)]
truth = [s["deforested"] for s in scenes]
t0_ = time.time()
cloud_det = [detect_cloud_shadow(s["t1"], s["t2"]) for s in scenes]
print(f"Cloud/shadow masks built in {time.time() - t0_:.1f}s")

# %% [markdown]
# ## 4. Baselines: classic index-threshold rules
#
# Three rules, each with a threshold **tuned on the training scenes** of each fold and then applied to the held-out scenes:
#
# 1. **dNDVI:** flag pixels where NDVI fell by more than a threshold
# 2. **dNBR:** the same with the normalised burn ratio (a standard forest-loss index)
# 3. **dNDVI + forest mask + cloud mask:** add the two most obvious pieces of context (was it forest? is the pixel cloudy?)

# %%
def forest_like(i1): return i1["ndvi"] > 0.7
RULES = {
    "dNDVI": lambda k, thr: (d_ndvi[k] < -thr),
    "dNBR": lambda k, thr: (d_nbr[k] < -thr),
    "dNDVI + forest mask + cloud mask": lambda k, thr: (d_ndvi[k] < -thr) & forest_like(ind1[k]) & ~cloud_det[k],
}
use_cloud_domain = {"dNDVI": False, "dNBR": False, "dNDVI + forest mask + cloud mask": True}
grid = np.arange(0.05, 0.75, 0.025)
base_pred = {name: [None] * len(scenes) for name in RULES}
base_thr = {name: [] for name in RULES}
for name, rule in RULES.items():
    for test in SCENE_FOLDS:
        train = [k for k in range(len(scenes)) if k not in test]
        best = max(grid, key=lambda thr: metrics(np.concatenate([rule(k, thr).ravel() for k in train]), np.concatenate([truth[k].ravel() for k in train]))["f1"])
        base_thr[name].append(round(best, 3))
        for k in test: base_pred[name][k] = rule(k, best)

def evaluate(pred_list, use_mask=False):
    domain = [~cloud_det[k] if use_mask else np.ones_like(truth[k], bool) for k in range(len(scenes))]
    p = np.concatenate([(pred_list[k] & domain[k]).ravel() for k in range(len(scenes))]); t = np.concatenate([(truth[k] & domain[k]).ravel() for k in range(len(scenes))])
    d = np.concatenate([domain[k].ravel() for k in range(len(scenes))])
    return metrics(p[d], t[d])

rows = []
for name in RULES:
    m = evaluate(base_pred[name], use_mask=use_cloud_domain[name]); rows.append({"method": name, **{k: m[k] for k in ["precision", "recall", "f1", "iou"]}, "tuned thresholds (4 folds)": base_thr[name]})
baseline_tbl = pd.DataFrame(rows)
baseline_tbl.round(3)

